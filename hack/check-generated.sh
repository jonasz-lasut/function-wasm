#!/usr/bin/env bash
# check-generated.sh is the drift check of the checked-in generated code:
# the protobuf codecs and the WIT bindings of the examples. A job
# regenerates them with the pinned generator and then runs this script,
# which fails when the working tree differs from what is checked in.
#
# One difference is allowed: the version a protobuf generator states in
# the header of a codec. A bump of protoc, protoc-gen-es or nanopb whose
# output is otherwise identical therefore passes with the old version
# still checked in, and the header moves the next time the output changes
# for real. Any other difference fails: a changed, added or removed line
# (one beside the version included), a file created, deleted or renamed, a
# changed file mode.
#
# The version lines are listed here and nowhere else. Each is tied to the
# file names its generator writes and to its whole line, and only the
# version in it may differ:
#
#   nanopb (*.pb.c, *.pb.h):
#     /* Generated by nanopb-0.4.9.1 */
#   protoc-gen-es (*_pb.js, *_pb.d.ts), the parameters compared:
#     // @generated by protoc-gen-es v2.17.0 with parameter "..."
#   protoc's Python generator (*_pb2.py), two places stating one version:
#     # Protobuf Python Version: 7.35.1
#     _runtime_version.ValidateProtobufRuntimeVersion(
#         _runtime_version.Domain.PUBLIC,
#         7,
#         35,
#         1,
#         '',
#     The second is a check at import: the protobuf runtime refuses a
#     codec generated by a protoc newer than itself and accepts an older
#     one of its major. A codec left at an older version therefore loads,
#     and the python example's tests load the checked-in codec on the
#     runtime its requirements.txt pins, so a version the runtime refuses
#     fails there.
#
# Everything else is compared whole. The WIT bindings are: wit-bindgen
# writes its version into every file and into the object beside the c
# bindings, so a wit-bindgen bump is a regeneration (make gen-bindings).
# protoc-gen-zig, protoc-gen-mbt and protoc's C# generator state no
# version.
#
# usage: check-generated.sh [-m <hint>] [<path>...]
#
# The paths (the whole repository when none is given) are read from the
# current directory, as git reads them; the hint is printed on a failure
# and says what to run. hack/check-generated-test.sh is the test.
set -euo pipefail

hint="the generated code is not up to date; regenerate it and commit the result"
while getopts m: opt; do
	case "$opt" in
	m) hint=$OPTARG ;;
	*)
		echo "usage: $0 [-m <hint>] [<path>...]" >&2
		exit 2
		;;
	esac
done
shift $((OPTIND - 1))
if [ $# -eq 0 ]; then
	set -- ':/'
fi

# normalise prints the file on stdin with every version stamp its name
# allows replaced by a fixed word, so two files that differ in a stamp's
# version alone print the same bytes. Each text rule replaces its first
# match only.
# shellcheck disable=SC2016
normalise='
use strict;
use warnings;

my $name = shift;
binmode STDIN;
binmode STDOUT;
local $/;
my $data = <STDIN>;
$data = "" unless defined $data;
my $version = qr/[0-9][0-9A-Za-z.+-]*/;

if ($name =~ /\.pb\.[ch]\z/) {
	$data =~ s{^/\* Generated by nanopb-$version \*/$}{/* Generated by nanopb-VERSION */}m;
} elsif ($name =~ /_pb\.(?:js|d\.ts)\z/) {
	$data =~ s{^// \@generated by protoc-gen-es v$version with parameter }{// \@generated by protoc-gen-es vVERSION with parameter }m;
} elsif ($name =~ /_pb2\.py\z/) {
	$data =~ s{^# Protobuf Python Version: $version$}{# Protobuf Python Version: VERSION}m;
	$data =~ s{^(_runtime_version\.ValidateProtobufRuntimeVersion\(\n    _runtime_version\.Domain\.PUBLIC,\n)    [0-9]+,\n    [0-9]+,\n    [0-9]+,\n    \x27[0-9A-Za-z.+-]*\x27,\n}{$1    VERSION,\n}m;
}
print $data;
'

top=$(git rev-parse --show-toplevel)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

drifted=()
stamped=()

# One entry of git status: the two status letters and the path, from the
# top of the repository.
judge() {
	local status=$1 path=$2
	if [ "$status" != " M" ] || [ ! -f "$top/$path" ] || [ -L "$top/$path" ]; then
		drifted+=("$status $path")
		return
	fi
	git cat-file blob ":$path" >"$work/checked-in"
	if cmp -s "$work/checked-in" "$top/$path"; then
		drifted+=("$status $path (the file mode)")
		return
	fi
	if perl -e "$normalise" "$path" <"$work/checked-in" >"$work/before" 2>/dev/null &&
		perl -e "$normalise" "$path" <"$top/$path" >"$work/after" 2>/dev/null &&
		cmp -s "$work/before" "$work/after"; then
		stamped+=("$path")
		return
	fi
	drifted+=("$status $path")
}

while IFS= read -r -d '' entry; do
	status=${entry:0:2}
	path=${entry:3}
	case "$status" in
	R* | C* | ?R | ?C)
		# A rename or a copy carries the path it came from as a second entry.
		IFS= read -r -d '' _ || true
		;;
	esac
	judge "$status" "$path"
done < <(git status --porcelain=v1 -z --untracked-files=all -- "$@")

if [ ${#drifted[@]} -gt 0 ]; then
	echo "$hint:"
	printf '%s\n' "${drifted[@]}"
	if [ ${#stamped[@]} -gt 0 ]; then
		echo "the generator's version alone differs, which is no drift, in:"
		printf '   %s\n' "${stamped[@]}"
	fi
	git --no-pager diff -- "$@"
	exit 1
fi
if [ ${#stamped[@]} -gt 0 ]; then
	echo "the generator's version alone differs from what is checked in, which is no drift, in:"
	printf '   %s\n' "${stamped[@]}"
fi
